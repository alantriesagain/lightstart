/**
 * @bootstrapp/light/tdom/width: grapheme segmentation and terminal cell
 * widths. Intl.Segmenter gives grapheme clusters; a cluster is as wide as
 * its first non-zero-width code point, forced to two cells by an emoji
 * presentation selector (U+FE0F). The wide table covers East Asian Wide
 * and Fullwidth and the emoji presentation ranges; it is small and
 * approximate by design.
 */

const segmenter = new Intl.Segmenter(undefined, { granularity: "grapheme" });

const isAscii = (s: string) => {
  for (let i = 0; i < s.length; i++) if (s.charCodeAt(i) >= 0x80) return false;
  return true;
};

/**
 * The grapheme clusters of `s`, one character each for ASCII.
 */
export const graphemes = (s: string): string[] => {
  const out: string[] = [];
  if (isAscii(s)) {
    for (let i = 0; i < s.length; i++) out.push(s.charAt(i));
    return out;
  }
  for (const part of segmenter.segment(s)) out.push(part.segment);
  return out;
};

