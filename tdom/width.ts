const inRanges = (cp: number, table: number[]) => {
  let lo = 0;
  let hi = table.length / 2 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const start = table[mid * 2];
    const end = table[mid * 2 + 1];
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
};

/**
 * Cells one code point takes: 0 (combining, control, joiner), 1, or 2 (wide).
 */
export const codePointWidth = (cp: number) => {
  if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0)) return 0;
  if (cp < 0x300) return 1;
  if (inRanges(cp, ZERO)) return 0;
  if (inRanges(cp, WIDE)) return 2;
  return 1;
};

/**
 * Cells one grapheme cluster takes.
 */
export const graphemeWidth = (g: string) => {
  if (g.length === 1) {
    const c = g.charCodeAt(0);
    if (c < 0x300) return c < 0x20 || (c >= 0x7f && c < 0xa0) ? 0 : 1;
  }
  let width = -1;
  let vs16 = false;
  for (let i = 0; i < g.length;) {
    const cp = g.codePointAt(i) ?? 0;
    i += cp > 0xffff ? 2 : 1;
    if (cp === 0xfe0f) vs16 = true;
    if (width < 0) {
      const w = codePointWidth(cp);
      if (w > 0) width = w;
    }
  }
  if (width < 0) width = 0;
  if (vs16 && width === 1) width = 2;
  return width;
};

/**
 * Cells a whole string takes.
 */
export const stringWidth = (s: string) => {
  if (isAscii(s)) {
    let w = 0;
    for (let i = 0; i < s.length; i++) {
      const c = s.charCodeAt(i);
      if (c >= 0x20 && c !== 0x7f) w++;
    }
    return w;
  }
  let w = 0;
  for (const g of graphemes(s)) w += graphemeWidth(g);
  return w;
};
