/** The native executable of the tsc-ts package light installs. */
const tscTsBinary = () => {
  const store = join(light, "node_modules", ".pnpm");
  const dir = readdirSync(store).find((entry) => entry.startsWith(`@tsc-ts+${process.platform}-${process.arch}`));
  if (!dir) throw new Error("no tsc-ts platform package under node_modules/.pnpm");
  const pkg = readdirSync(join(store, dir, "node_modules", "@tsc-ts"))[0];
  return join(store, dir, "node_modules", "@tsc-ts", pkg, "lib", "tsc-ts");
};

const measures = () => {
  const tsgo = process.env.TSGO;
  const tscTsExe = tscTsBinary();
  const checkers = [
    {
      id: "ts6",
      label: "TypeScript",
      version: JSON.parse(readFileSync(join(light, "node_modules", "typescript", "package.json"), "utf8")).version,
      command: process.execPath,
      args: [join(light, "node_modules", "typescript", "bin", "tsc")],
      sizeBytes: /** @type {number | null} */ (null),
    },
    ...(tsgo ? [{ id: "tsgo", label: "tsgo", version: firstLine(run(tsgo, ["--version"], light).stdout).replace("Version ", ""), command: tsgo, args: [], sizeBytes: statSync(tsgo).size }] : []),
    { id: "tsc-ts", label: "tsc-ts", version: tscTsVersion, command: tscTsExe, args: [], sizeBytes: statSync(tscTsExe).size },
  ];

  const outputs = new Set();
  const typecheck = checkers.map((checker) => {
    const result = measure(checker.command, [...checker.args, "--noEmit", "-p", "."], light, 3);
    outputs.add(result.stdout);
    return { id: checker.id, label: checker.label, version: checker.version, ms: result.ms, rssKb: result.rssKb, errors: (result.stdout.match(/error TS\d+/g) ?? []).length, sizeBytes: checker.sizeBytes };
  });
  const files = tsgo ? run(tsgo, ["--noEmit", "-p", ".", "--listFilesOnly"], light).stdout.trim().split("\n").length : null;

  const benchDir = mkdtempSync(join(tmpdir(), "light-native-bench-"));
  try {
    const binary = join(benchDir, "bench");
    run(scriptc, ["build", "native/bench.js", "-o", binary, "--strip"], light);
    /** @param {string} output @returns {Record<string, number>} */
    const steps = (output) =>
      Object.fromEntries(
        output
          .trim()
          .split("\n")
          .map((line) => {
            const [step, ms] = line.split(": ");
            return [step, Number.parseFloat(ms)];
          }),
      );
    /** The fastest of three runs for each step. @param {string} command @param {string[]} args */
    const fastest = (command, args) => {
      const runs = [0, 1, 2].map(() => steps(run(command, args, light).stdout));
      return Object.fromEntries(Object.keys(runs[0]).map((step) => [step, Math.min(...runs.map((r) => r[step]))]));
    };
    const node = fastest(process.execPath, ["native/bench.js"]);
    const native = fastest(binary, []);
    const coverage = coverageOf(run(scriptc, ["coverage", "native/index.js", "--fail-on=slow-paths"], light).stdout, light);
    const repo = process.env.SCRIPTC_REPO;
    const corpus = repo && existsSync(repo) ? run("pnpm", ["exec", "vitest", "list", "tests/harness/llvm-differential.test.ts"], repo).stdout.trim().split("\n").length : null;
    return {
      tools,
      typecheck: { files, sameDiagnostics: outputs.size === 1, checkers: typecheck },
      bench: { steps: Object.keys(node).map((step) => ({ step, node: node[step], native: native[step] })), sizeBytes: statSync(binary).size },
      coverage: { statements: Number(/compile statically\s+(\d+)/.exec(coverage)?.[1] ?? 0), text: coverage },
      corpus,
    };
  } finally {
    rmSync(benchDir, { recursive: true, force: true });
  }
};

