import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { cpus, loadavg, tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scriptcPath } from "@bootstrapp/light/native/scriptc.js";

const website = join(dirname(fileURLToPath(import.meta.url)), "..");
const light = join(website, "..");
const examplesDir = join(website, "native-examples");
const scriptc = scriptcPath(light);
const tscTs = join(light, "node_modules", ".bin", "tsc-ts");
const RUNS = 15;

/**
 * @param {string} command
 * @param {string[]} args
 * @param {string} cwd
 * @param {{ check?: boolean }} [options]
 */
const run = (command, args, cwd, { check = true } = {}) => {
  const result = spawnSync(command, args, { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, env: { ...process.env, SCRIPTC_NO_CACHE: "1" } });
  if (result.error) throw result.error;
  if (check && result.status !== 0) throw new Error(`${command} ${args.join(" ")} exited ${result.status}\n${result.stderr}`);
  return result;
};

/** @param {string} text */
const firstLine = (text) => text.trim().split("\n")[0];

/** @param {number} value */
const tenth = (value) => Math.round(value * 10) / 10;

/**
 * Wall time (the fastest of `runs`, which a busy machine disturbs least) and
 * peak resident memory of one program.
 * @param {string} command
 * @param {string[]} args
 * @param {string} cwd
 * @param {number} [runs]
 */
const measure = (command, args, cwd, runs = RUNS) => {
  /** @type {number[]} */
  const times = [];
  let result = run(command, args, cwd, { check: false });
  for (let i = 0; i < runs; i++) {
    const start = process.hrtime.bigint();
    result = run(command, args, cwd, { check: false });
    times.push(Number(process.hrtime.bigint() - start) / 1e6);
  }
  const timed = run("/usr/bin/time", ["-f", "%M", command, ...args], cwd, { check: false });
  const rssKb = Number(timed.stderr.trim().split("\n").at(-1));
  return { stdout: result.stdout, stderr: result.stderr, status: result.status, ms: tenth(Math.min(...times)), rssKb };
};

/** @param {string} text */
const withoutAddresses = (text) => text.replace(/ \(sfi = 0x[0-9a-f]+\)/g, "").replace(/0x[0-9a-f]+ /g, "").replace(/, caller SP 0x[0-9a-f]+, pc 0x[0-9a-f]+/, "");

/**
 * The bytecode V8's Ignition interpreter runs for one function, without the
 * addresses and source positions.
 * @param {string} text
 */
const bytecodeOf = (text) => {
  const lines = text.split("\n");
  const start = lines.findIndex((line) => line.startsWith("[generated bytecode"));
  const end = lines.findIndex((line, i) => i > start && line.startsWith("Handler Table"));
  return lines
    .slice(start + 1, end)
    .filter((line) => !/^\s*(0x[0-9a-f]+: \[|- map:|- length:)/.test(line))
    .map((line) => line.replace(/^\s*(\d+ [SE]> )?\s*0x[0-9a-f]+ /, "").replace(/0x[0-9a-f]+ /g, ""))
    .join("\n")
    .trim();
};

/**
 * The lines of node's optimization trace about the named functions (`""` for
 * the module's top level, an anonymous function), without addresses.
 * @param {string} text
 * @param {string[]} functions
 */
const traceOf = (text, functions) =>
  text
    .split("\n")
    .filter((line) => line.startsWith("[") && functions.some((name) => line.includes(name ? `<JSFunction ${name} ` : "<JSFunction (sfi")))
    .map(withoutAddresses)
    .join("\n");

/**
 * The machine code an optimizing compiler made for the named function: its
 * kind, the instructions up to its first return (addresses and raw bytes
 * removed, each jump to a deoptimization exit labelled with the reason V8
 * notes there), and those reasons in order.
 * @param {string} text
 * @param {string} name
 */
const optimizedCodeOf = (text, name) => {
  const all = text.split("\n");
  const lines = all.slice(Math.max(0, all.findIndex((line) => line === `name = ${name}`) - 1));
  const kind = (lines.find((line) => line.startsWith("kind = ") || line.startsWith("compiler = ")) ?? "").replace(/^(kind|compiler) = /, "");
  const start = lines.findIndex((line) => line.startsWith("Instructions"));
  /** @type {{ offset: string, text: string }[]} */
  const instructions = [];
  /** @type {Map<string, string>} */
  const exits = new Map();
  let last = "";
  for (const line of lines.slice(start + 1)) {
    const match = /^0x[0-9a-f]+\s+([0-9a-f]+)\s+[0-9a-f]+\s+(.*)$/.exec(line);
    if (match) {
      last = match[1];
      instructions.push({ offset: match[1], text: match[2] });
      continue;
    }
    const reason = /;; debug: deopt reason '([^']+)'/.exec(line);
    if (reason) exits.set(last, reason[1]);
    else if (line.trim() && !line.trimStart().startsWith(";;")) break;
  }
  const end = instructions.findIndex((instruction) => /^ret\b/.test(instruction.text));
  const code = instructions.slice(0, end + 1).map(({ offset, text }) => {
    const target = /<\+0x([0-9a-f]+)>/.exec(text)?.[1];
    const exit = target && exits.get(target);
    const clean = text
      .replace(/0x[0-9a-f]+\s+<\+0x([0-9a-f]+)>/, "+$1")
      .replace(/\s+;;\s+object: 0x[0-9a-f]+ (<.*>)/, "  ;; $1")
      .replace(/\s+\(external value \((.*)\)\)$/, "  ;; $1")
      .replace(/\s+\((\w+)\)\s+;;\s+near builtin entry/, "  ;; $1")
      .replace(/0x[0-9a-f]{8,}/g, "0x…");
    return `${offset.padStart(3)}  ${clean}${exit ? `  ;; deopt: ${exit}` : ""}`;
  });
  return { kind, code: code.join("\n"), exits: [...exits.values()] };
};

/** @param {string} key @param {unknown} value */
const withoutLocations = (key, value) => (key === "loc" || key === "source" ? undefined : value);
/** @param {unknown} value */
const irJson = (value) => JSON.stringify(value, withoutLocations, 2);

/**
 * `name(param types): return type` for each function the program defines.
 * @param {any} module
 */
const signaturesOf = (module) => {
  /** @param {any} type @returns {string} */
  const spell = (type) => {
    if (type.kind === "union") return type.unionId;
    if (type.kind === "record") return type.shapeId;
    if (type.kind === "object") return type.className;
    if (type.kind === "array") return `${spell(type.elem)}[]`;
    if (type.kind === "func") return `(${type.params.map(spell).join(", ")}) => ${spell(type.ret)}`;
    return type.kind;
  };
  return module.functions
    .filter((/** @type {any} */ fn) => !fn.name.startsWith("%init") && fn.name !== "%main")
    .map((/** @type {any} */ fn) => `${fn.name}(${fn.params.map((/** @type {any} */ p) => spell(p.type)).join(", ")}): ${spell(fn.returnType)}`)
    .join("\n");
};

/**
 * Lines of the LLVM module: the class's struct type, every function emitted
 * for the method, the first call of it from another function, and the
 * class's reference-count release.
 * @param {string} text
 * @param {string} className
 * @param {string} method
 */
const llvmOf = (text, className, method) => {
  const lines = text.split("\n");
  const struct = lines.find((line) => line.startsWith(`%sc_o_${className} = type`)) ?? "";
  const name = `__x25_${className}_${method}`;
  /** @param {number} at */
  const functionAt = (at) => lines.slice(at, lines.findIndex((line, j) => j > at && line === "}") + 1).join("\n");
  /** @type {string[]} */
  const functions = [];
  let call = "";
  let inMethod = false;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].startsWith("define")) inMethod = lines[i].includes(name);
    if (!call && !inMethod && /\bcall\b/.test(lines[i]) && lines[i].includes(name)) call = lines[i].trim();
    if (lines[i].startsWith("define") && inMethod) functions.push(functionAt(i));
  }
  const release = lines.findIndex((line) => line.startsWith(`define internal void @sc_release_${className}(`));
  return { struct, functions: functions.join("\n\n"), call, release: release >= 0 ? functionAt(release) : "" };
};

/**
 * The loop of the optimized assembly that holds the first floating-point add:
 * the three instructions that set it up, the loop, and the store after it.
 * @param {string} text
 */
const loopOf = (text) => {
  const lines = text.split("\n").filter((line) => !/^\s*\.(cfi_|p2align|file|loc)/.test(line));
  const first = lines.findIndex((line) => /^\s+addsd\s/.test(line));
  let label = first;
  while (label > 0 && !/^\.LBB\S+:/.test(lines[label])) label--;
  let end = first;
  while (end < lines.length && !/^\s+jne\s/.test(lines[end])) end++;
  return lines.slice(Math.max(0, label - 3), end + 2).join("\n");
};

/** A coverage report with the scratch directory taken out of its paths. @param {string} text @param {string} dir */
const coverageOf = (text, dir) => text.replaceAll(`${dir}/`, "").trim();

/** The runtime pack and objects a program links, from `--print=native-link-info`. @param {string} text */
const linkOf = (text) => {
  const info = JSON.parse(text);
  const objects = info.runtime_pack.objects ?? [];
  return {
    pack: `${info.runtime_pack.package}@${info.runtime_pack.version}`,
    flavor: info.runtime_pack.flavor,
    target: info.target.name,
    objects: objects.length,
    bytes: objects.reduce((/** @type {number} */ sum, /** @type {{ size?: number }} */ object) => sum + (object.size ?? 0), 0),
    abi: info.runtime_abi.marker,
  };
};

/**
 * A copy of an example in a scratch directory, with its JavaScript as tsc-ts
 * writes it (`js/<name>.mjs`, so node runs it as a module).
 * @param {string} path the example's path under `native-examples/`
 */
const stage = (path) => {
  const file = basename(path);
  const dir = mkdtempSync(join(tmpdir(), `light-native-${basename(file, ".ts")}-`));
  copyFileSync(join(examplesDir, path), join(dir, file));
  const stem = basename(file, ".ts");
  run(tscTs, [file, "--target", "es2024", "--module", "esnext", "--outDir", "js"], dir);
  copyFileSync(join(dir, "js", `${stem}.js`), join(dir, "js", `${stem}.mjs`));
  mkdirSync(join(dir, "out"));
  return {
    dir,
    source: readFileSync(join(examplesDir, path), "utf8"),
    javascript: readFileSync(join(dir, "js", `${stem}.js`), "utf8"),
    script: join("js", `${stem}.mjs`),
    /** @param {string} emit */
    emit: (emit) => {
      const out = join("out", `${stem}.${emit}`);
      run(scriptc, ["build", file, `--emit=${emit}`, "-o", out], dir);
      return readFileSync(join(dir, out), "utf8");
    },
    build: () => {
      run(scriptc, ["build", file, "-o", join("out", stem)], dir);
      return join(dir, "out", stem);
    },
    coverage: () => coverageOf(run(scriptc, ["coverage", file, "--fail-on=slow-paths"], dir, { check: false }).stdout, dir),
    /** @param {string[]} flags */
    node: (flags) => run(process.execPath, [...flags, join("js", `${stem}.mjs`)], dir, { check: false }),
    done: () => rmSync(dir, { recursive: true, force: true }),
  };
};

/** @param {string} a @param {string} b @param {string} what */
const same = (a, b, what) => {
  if (a !== b) throw new Error(`${what}: node printed ${JSON.stringify(a)}, the executable ${JSON.stringify(b)}`);
};

