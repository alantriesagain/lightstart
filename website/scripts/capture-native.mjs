const captureTypes = () => {
  /** @type {Record<string, unknown>} */
  const out = {};
  for (const spec of TYPES) {
    const s = stage(`types/${spec.id}.ts`);
    try {
      const types = typesOf(JSON.parse(s.emit("ir")), s.emit("llvm"), spec.fns, spec.bodies ?? []);
      const binary = s.build();
      const node = selfTimed(() => s.node([]));
      const native = selfTimed(() => run(binary, [], s.dir, { check: false }));
      const data = { ...types, same: node.stdout === native.stdout };
      const failed = spec.facts(data).filter(([, holds]) => !holds).map(([fact]) => fact);
      if (failed.length) throw new Error(`types/${spec.id}.ts no longer shows: ${failed.join("; ")}. Update its text in lib/native/topic-types.js and its facts here.`);
      out[spec.id] = { file: `${spec.id}.ts`, source: s.source, ...data, coverage: s.coverage(), node, native };
      console.log(`  ${spec.id}: node ${node.ms} ms, native ${native.ms} ms${data.same ? "" : ", output differs"}`);
    } finally {
      s.done();
    }
  }
  return { tools, examples: out };
};

/** The optimization page's pairs, `native-examples/fast/<id>-slow.ts` and `-fast.ts`: the same work written two ways. */
const PAIRS = ["any", "unknown", "dictionary", "dispatch", "exceptions", "allocation", "shapes", "delete", "literals", "interfaces", "strings"];

const capturePairs = () => {
  /** @type {Record<string, unknown>} */
  const out = {};
  /** The throwing version's time under node with stack traces turned off. */
  let stacklessThrow = 0;
  for (const id of PAIRS) {
    const staged = { slow: stage(`fast/${id}-slow.ts`), fast: stage(`fast/${id}-fast.ts`) };
    try {
      const binaries = { slow: staged.slow.build(), fast: staged.fast.build() };
      /** @type {Record<"slow" | "fast", { node: number[], native: number[], printed: string }>} */
      const times = { slow: { node: [], native: [], printed: "" }, fast: { node: [], native: [], printed: "" } };
      /** One timed run: the milliseconds the program printed on stderr. @param {{ stdout: string, stderr: string }} result */
      const timeOf = (result) => Number.parseFloat(result.stderr.trim().split("\n").at(-1) ?? "");
      // Interleaved, so both versions run under the same load; a warm-up round first.
      for (let round = 0; round <= 7; round++)
        for (const variant of /** @type {const} */ (["slow", "fast"])) {
          const node = staged[variant].node([]);
          const native = run(binaries[variant], [], staged[variant].dir, { check: false });
          same(node.stdout, native.stdout, `fast/${id}-${variant}.ts`);
          times[variant].printed = node.stdout;
          if (round === 0) continue;
          times[variant].node.push(timeOf(node));
          times[variant].native.push(timeOf(native));
        }
      if (times.slow.printed !== times.fast.printed) throw new Error(`fast/${id}: the slow and fast versions print different results`);
      const variants = Object.fromEntries(
        /** @type {const} */ (["slow", "fast"]).map((variant) => [variant, { source: staged[variant].source, node: tenth(Math.min(...times[variant].node)), native: tenth(Math.min(...times[variant].native)) }]),
      );
      if (id === "exceptions") stacklessThrow = selfTimed(() => staged.slow.node(["--stack-trace-limit=0"]), 7).ms;
      out[id] = variants;
      console.log(`  ${id}: node ${variants.slow.node} -> ${variants.fast.node} ms, native ${variants.slow.native} -> ${variants.fast.native} ms`);
    } finally {
      staged.slow.done();
      staged.fast.done();
    }
  }
  const probe = run(
    process.execPath,
    ["--allow-natives-syntax", "-e", 'const a = { id: 1, label: "x" }; const b = { id: 1, label: "x" }; const before = %HasFastProperties(a); delete a.label; b.label = undefined; console.log(JSON.stringify({ before, afterDelete: %HasFastProperties(a), afterAssign: %HasFastProperties(b) }))'],
    website,
  );
  return { tools, pairs: out, deleteProbe: JSON.parse(probe.stdout), stacklessThrow };
};

