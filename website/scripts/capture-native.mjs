/**
 * The artifacts the /native pages show, captured from the real tools. Outputs
 * are trimmed (addresses, source positions and unrelated functions removed),
 * never rewritten.
 *
 * Without arguments, every program in `native-examples/` goes through tsc-ts
 * (the JavaScript a browser or node runs), node's bytecode printer, its
 * optimizing compilers' traces and code, and every scriptc stage (typed IR,
 * LLVM IR, assembly, coverage, the executable); both builds run to compare
 * output, time and memory. Writes `lib/native/captures.js`.
 *
 *   SCRIPTC=scriptc-dev node scripts/capture-native.mjs
 *
 * With `--measures`, the slow measurements: TypeScript 6, tsgo and tsc-ts
 * checking light's project, light's native benchmark under node and as a
 * binary, its coverage, and the size of scriptc's test corpus. `TSGO` names a
 * tsgo executable (TypeScript 7.0.2's `tsc`) and `SCRIPTC_REPO` a scriptc
 * checkout; either can be left out. Writes `lib/native/measures.js`.
 *
 *   SCRIPTC=scriptc-dev TSGO=<tsgo> SCRIPTC_REPO=<scriptc> node scripts/capture-native.mjs --measures
 *
 * With `--types`, the programs in `native-examples/types/`: their IR types,
 * the functions their hot code calls, coverage and the time under node and
 * natively, with the facts the types page states about each checked; writes
 * `lib/native/captures-types.js`. With `--pairs`, each pair in
 * `native-examples/fast/` (the same work written two ways) timed under node
 * and natively, the two versions' runs interleaved so both see the same load;
 * writes `lib/native/captures-pairs.js`. Flags combine.
 *
 * Run it again after a scriptc, tsc-ts or node upgrade.
 */
