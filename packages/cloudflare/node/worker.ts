/**
 * @file The app's server as a Pages Worker: whether the project has a server
 * (`@lightstart/api` in its package.json), the `.light/worker.ts` entry that
 * answers `/api/*` through the generated `createServer` and hands every other
 * request to `env.ASSETS`, the esbuild bundle of it into one ESM file, and the
 * staged copy of a build with `_worker.js` and `_routes.json` added. The build
 * folder itself is never changed.
 */

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

import * as esbuild from "esbuild";
import { writeServerEntry } from "@lightstart/api/node/server-entry.ts";

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);

const declares = (project: string, name: string): boolean => {
  const file = join(project, "package.json");
  if (!existsSync(file)) return false;
  const pkg: unknown = JSON.parse(readFileSync(file, "utf8"));
  if (!isRecord(pkg)) return false;
  for (const key of ["dependencies", "devDependencies", "peerDependencies"]) {
    const deps = pkg[key];
    if (isRecord(deps) && name in deps) return true;
  }
  return false;
};

/** Whether the project's `package.json` declares `@lightstart/api`, so it has a server to bundle. */
export const hasServer = (project: string): boolean => declares(project, "@lightstart/api");

const sourceOf = (): string => {
  const lines: string[] = [];
  lines.push("/**");
  lines.push(" * @file Generated by @lightstart/cloudflare: the app's server as a Pages Worker. Do not edit.");
  lines.push(" */");
  lines.push("");
  lines.push('import type { D1Like } from "@lightstart/api/server";');
  lines.push('import { toFetch } from "@lightstart/server/fetch";');
  lines.push('import { createServer } from "./server.ts";');
  lines.push("");
  lines.push("interface WorkerEnv {");
  lines.push("  DB: D1Like;");
  lines.push("  ASSETS: { fetch(request: Request): Promise<Response> };");
  lines.push("  [key: string]: unknown;");
  lines.push("}");
  lines.push("");
  lines.push("interface Platform {");
  lines.push("  waitUntil(work: Promise<unknown>): void;");
  lines.push("}");
  lines.push("");
  lines.push("type Handler = ReturnType<typeof toFetch>;");
  lines.push("");
  lines.push("let handler: Handler | null = null;");
  lines.push("");
  lines.push("const handlerFor = (env: WorkerEnv): Handler => {");
  lines.push("  if (handler === null) {");
  lines.push("    handler = toFetch(createServer({ db: () => env.DB, env }));");
  lines.push("  }");
  lines.push("  return handler;");
  lines.push("};");
  lines.push("");
  lines.push("export default {");
  lines.push("  async fetch(request: Request, env: WorkerEnv, ctx: Platform): Promise<Response> {");
  lines.push("    const path = new URL(request.url).pathname;");
  lines.push('    if (path === "/api" || path.startsWith("/api/")) return handlerFor(env)(request, env, ctx);');
  lines.push("    return env.ASSETS.fetch(request);");
  lines.push("  },");
  lines.push("};");
  lines.push("");
  return lines.join("\n");
};

/** Write `<project>/.light/worker.ts`, the entry the bundle starts from, and answer its path. */
export const workerSource = async (project: string): Promise<string> => {
  await writeServerEntry(project);
  const entry = join(project, ".light", "worker.ts");
  mkdirSync(join(project, ".light"), { recursive: true });
  writeFileSync(entry, sourceOf());
  return entry;
};

const nodeImports = (result: esbuild.BuildResult): string[] => {
  const found = new Set<string>();
  for (const output of Object.values(result.metafile?.outputs ?? {})) {
    for (const imported of output.imports) if (imported.path.startsWith("node:")) found.add(imported.path);
  }
  return [...found].sort();
};

const messageOf = (error: unknown): string => {
  if (!isRecord(error)) return String(error);
  const errors = error["errors"];
  if (Array.isArray(errors)) {
    const said = errors
      .map((item) => (isRecord(item) && typeof item["text"] === "string" ? item["text"] : ""))
      .filter((text) => text !== "");
    if (said.length > 0) return said.join("; ");
  }
  return typeof error["message"] === "string" ? error["message"] : String(error);
};

/** Bundle `.light/worker.ts` into one ESM file for a Pages Worker; a `node:` module in it is an error. */
export const bundleWorker = async (project: string, outFile: string): Promise<void> => {
  const entry = await workerSource(project);
  let result: esbuild.BuildResult;
  try {
    result = await esbuild.build({
      entryPoints: [entry],
      outfile: outFile,
      bundle: true,
      write: true,
      format: "esm",
      platform: "neutral",
      target: "es2022",
      conditions: ["worker", "browser"],
      mainFields: ["module", "main"],
      absWorkingDir: project,
      external: ["node:*"],
      metafile: true,
      logLevel: "silent",
    });
  } catch (error) {
    throw new Error(`Bundling the app's server failed: ${messageOf(error)}`);
  }
  const reached = nodeImports(result);
  if (reached.length > 0) throw new Error(`The app's server reaches a Node module (${reached.join(", ")}); a Pages Worker has no Node built-ins`);
};

/** Copy a build to `.deployed/staged/<id>` with `_worker.js` and `_routes.json`; answer the staged folder. */
export const stageDeploy = async (buildDir: string, project: string): Promise<string> => {
  const id = basename(buildDir);
  const staged = join(project, ".deployed", "staged", id);
  rmSync(staged, { recursive: true, force: true });
  cpSync(buildDir, staged, { recursive: true });
  await bundleWorker(project, join(staged, "_worker.js"));
  writeFileSync(join(staged, "_routes.json"), JSON.stringify({ version: 1, include: ["/api/*"], exclude: [] }));
  return staged;
};
