/**
 * @file The band layout a canvas's `build.mjs` calls: each band a title and a note, its boards in a
 * row with a gap, a board's own note under it. It writes each board's HTML, `canvas.json` and
 * `BOARDS.md` into the canvas folder.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { CanvasIndex, LayoutBand, LayoutCanvas, LayoutOptions } from "./types.ts";

const DEFAULTS: Required<LayoutOptions> = {
  gap: 120,
  bandTitleMaxWidth: 1600,
  bandNoteWidth: 900,
  bandNoteOffset: 80,
  bandNoteToBoards: 70,
  boardNoteGap: 30,
  bandGap: 220,
  noteMinWidth: 360,
  noteMaxWidth: 620,
  notePadding: 32,
  noteCharWidth: 7.1,
  noteLineHeight: 19,
  noteChrome: 32,
};

const bandLabel = (band: LayoutBand): string => (band.date ? `${band.title} · ${band.date}` : band.title);

const noteHeight = (text: string, width: number, options: Required<LayoutOptions>): number => {
  const perLine = Math.max(20, Math.floor((width - options.notePadding) / options.noteCharWidth));
  const lines = text.split("\n").reduce((n, part) => n + Math.max(1, Math.ceil(part.length / perLine)), 0);
  return lines * options.noteLineHeight + options.noteChrome;
};

const noteWidth = (width: number, options: Required<LayoutOptions>): number => Math.min(Math.max(width, options.noteMinWidth), options.noteMaxWidth);

/**
 * Lay a canvas out in bands and write its boards, `canvas.json` and `BOARDS.md` into `dir`.
 *
 * @param dir The canvas folder.
 * @param canvas Its title and bands.
 * @param options The distances and note measurements; each defaults to the band layout's own.
 * @returns How many boards it wrote.
 */
export const layoutCanvas = (dir: string, canvas: LayoutCanvas, options: LayoutOptions = {}): number => {
  const settings = { ...DEFAULTS, ...options };
  mkdirSync(dir, { recursive: true });
  const boards: CanvasIndex["boards"] = {};
  const notes: CanvasIndex["notes"] = {};
  const order: string[] = [];
  let y = 0;
  const md = ["Generated by build.mjs on every build: edit its source, not this file.", "", `# ${canvas.title}`, ""];
  canvas.bands.forEach((band, b) => {
    const label = bandLabel(band);
    notes[`band-${b}`] = { x: 0, y, text: label, kind: "title1", maxW: settings.bandTitleMaxWidth };
    const noteW = settings.bandNoteWidth;
    notes[`band-${b}-note`] = { x: 0, y: y + settings.bandNoteOffset, w: noteW, text: band.note };
    const top = y + settings.bandNoteOffset + noteHeight(band.note, noteW, settings) + settings.bandNoteToBoards;
    let x = 0;
    let bottom = top;
    md.push(`## ${label}`, "", band.note, "");
    for (const board of band.boards) {
      boards[board.file] = { x, y: top, w: board.w, h: board.h, title: board.title };
      order.push(board.file);
      writeFileSync(join(dir, board.file), board.html);
      let end = top + board.h;
      if (board.note) {
        const width = noteWidth(board.w, settings);
        notes[board.file.replace(".dc.html", "")] = { x, y: end + settings.boardNoteGap, w: width, text: board.note };
        end += settings.boardNoteGap + noteHeight(board.note, width, settings);
      }
      bottom = Math.max(bottom, end);
      md.push(`- ${board.file.replace(".dc.html", "")}: ${board.title}`);
      x += board.w + settings.gap;
    }
    md.push("");
    y = bottom + settings.bandGap;
  });
  const previous = existsSync(join(dir, "canvas.json")) ? (JSON.parse(readFileSync(join(dir, "canvas.json"), "utf8")) as Record<string, unknown>) : {};
  const index: CanvasIndex = {
    ...previous,
    v: 3,
    title: canvas.title,
    launch: previous["launch"] ?? { view: "canvas" },
    pages: previous["pages"] ?? [],
    boards,
    order,
    notes,
    designSystems: previous["designSystems"] ?? [],
  };
  writeFileSync(join(dir, "canvas.json"), JSON.stringify(index, null, 2) + "\n");
  writeFileSync(join(dir, "BOARDS.md"), md.join("\n"));
  return order.length;
};
